#!/usr/bin/env node
/**
 * Turns the traced streak-flame silhouettes (streak-flame-contours.json) into
 * smooth SVG path strings for the flat, vector-drawn flame.
 *
 * The contours are closed polygons in the 512 × 512 reference frame. They are
 * moved into the flame's crop (CROP below, the same frame the app sizes the
 * flame by) and smoothed with a closed Catmull-Rom spline written as cubic
 * Béziers, so the outline stays round at any size.
 *
 * Output: components/streak-celebration/streak-flame-paths.ts
 * Usage:  node scripts/generate-streak-flame-paths.js
 */
"use strict";

const fs = require("fs");
const path = require("path");

const CONTOURS = require("./streak-flame-contours.json");
const OUT = path.join(path.dirname(require.resolve("./streak-flame-contours.json")), "..", "components", "streak-celebration", "streak-flame-paths.ts");

// Crop of the reference frame that holds the flame.
const CROP = { x: 104, y: 52, w: 304, h: 404 };

const round = (v) => Math.round(v * 10) / 10;

function toPath(points) {
  const pts = points.map(([x, y]) => [x - CROP.x, y - CROP.y]);
  const n = pts.length;
  const at = (i) => pts[(i + n) % n];
  let d = `M${round(pts[0][0])} ${round(pts[0][1])}`;
  for (let i = 0; i < n; i++) {
    const p0 = at(i - 1);
    const p1 = at(i);
    const p2 = at(i + 1);
    const p3 = at(i + 2);
    const c1 = [p1[0] + (p2[0] - p0[0]) / 6, p1[1] + (p2[1] - p0[1]) / 6];
    const c2 = [p2[0] - (p3[0] - p1[0]) / 6, p2[1] - (p3[1] - p1[1]) / 6];
    d += `C${round(c1[0])} ${round(c1[1])} ${round(c2[0])} ${round(c2[1])} ${round(p2[0])} ${round(p2[1])}`;
  }
  return `${d}Z`;
}

const source = `// Generated by scripts/generate-streak-flame-paths.js — do not edit by hand.

/** Size of the frame the paths are drawn in. */
export const STREAK_FLAME_FRAME = { width: ${CROP.w}, height: ${CROP.h} } as const;

/** Orange outer flame. */
export const STREAK_FLAME_OUTER = "${toPath(CONTOURS.outer)}";

/** Yellow inner flame. */
export const STREAK_FLAME_INNER = "${toPath(CONTOURS.inner)}";
`;

fs.writeFileSync(OUT, source);
console.log(`Wrote ${path.relative(process.cwd(), OUT)}`);
